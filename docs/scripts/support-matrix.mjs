// Generates docs/docs/platforms/_support-matrix.md from what the generators claim.
//
// Each generator declares its supported annotations and attributes with @GeneratorFeature; the
// build turns that into META-INF/cloudhopper/<generatorId>-features.json. The same files drive the
// build warnings and the TCK test selection, so the documentation shows exactly those claims.
// Run after the generator modules have been compiled (mvn install); runs as "prebuild"/"prestart".

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const docsDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repoDir = path.dirname(docsDir);
const output = path.join(docsDir, 'docs', 'platforms', '_support-matrix.md');

const TARGETS = [
  {id: 'aws-terraform', label: 'AWS', module: 'generator-aws-terraform'},
  {id: 'azure-terraform', label: 'Azure', module: 'generator-azure-terraform'},
  {id: 'gcp-terraform', label: 'GCP', module: 'generator-gcp-terraform'},
  {id: 'springboot-http', label: 'Spring Boot', module: 'generator-springboot'},
];

// Annotations the feature system covers, in the order they appear in the guide
const ANNOTATIONS = ['Function', 'HttpTrigger', 'ScheduledTrigger', 'EventTrigger'];
// Attributes outside the feature system: vendor extensions are meant for one target only
const EXEMPT = new Set(['Function.extensions']);

const annotationDir = path.join(repoDir, 'deployment-config-api', 'src', 'main', 'java', 'eu', 'cloudhopper', 'mc', 'annotations');

/** The attributes (element methods) declared directly in an annotation type. */
function attributesOf(annotation) {
  const source = fs.readFileSync(path.join(annotationDir, annotation + '.java'), 'utf8');
  return [...source.matchAll(/^ {4}[A-Za-z][\w[\]<>.]* (\w+)\(\)(?: default [^;]+)?;/gm)].map((m) => m[1]);
}

function loadClaims(target) {
  const file = path.join(repoDir, target.module, 'target', 'classes', 'META-INF', 'cloudhopper', target.id + '-features.json');
  if (!fs.existsSync(file)) {
    return null;
  }
  const claims = new Map();
  for (const feature of JSON.parse(fs.readFileSync(file, 'utf8')).features) {
    const simpleName = feature.supportedAnnotation.substring(feature.supportedAnnotation.lastIndexOf('.') + 1);
    claims.set(simpleName, new Set(feature.supportedAttributes));
  }
  return claims;
}

const claims = TARGETS.map(loadClaims);
let text;
if (claims.some((c) => c === null)) {
  const missing = TARGETS.filter((_, i) => claims[i] === null).map((t) => t.module).join(', ');
  if (process.env.CI === 'true') {
    // the deploy workflow builds the generators first; publishing a placeholder would hide that it failed
    console.error(`support-matrix: no features file for ${missing}`);
    process.exit(1);
  }
  console.warn(`support-matrix: no features file for ${missing}; run "mvn install" first. Writing a placeholder.`);
  text = ':::note\n\nThe support matrix is generated from the generator modules. Build them with '
      + '`mvn install` and rebuild the site to see it.\n\n:::\n';
} else {
  const header = `| | ${TARGETS.map((t) => t.label).join(' | ')} |\n|---|${TARGETS.map(() => ':-:').join('|')}|\n`;
  const rows = [];
  for (const annotation of ANNOTATIONS) {
    rows.push(`| **\`@${annotation}\`** | ${TARGETS.map((_, i) => (claims[i].has(annotation) ? '✓' : '–')).join(' | ')} |`);
    for (const attribute of attributesOf(annotation)) {
      if (EXEMPT.has(`${annotation}.${attribute}`)) {
        continue;
      }
      const cells = TARGETS.map((_, i) => (claims[i].get(annotation)?.has(attribute) ? '✓' : '–'));
      rows.push(`| &nbsp;&nbsp;\`${attribute}\` | ${cells.join(' | ')} |`);
    }
  }
  text = '{/* Generated by docs/scripts/support-matrix.mjs from the generators\' features files; do not edit. */}\n\n'
      + header + rows.join('\n') + '\n';
}
fs.writeFileSync(output, text);
console.log(`support-matrix: wrote ${path.relative(repoDir, output)}`);

/**
 * A table operation is not allowed: the {@code @Table} parameter does not declare the access, or
 * the platform refused it, e.g. because the function's identity lacks a permission.
 */
public class KeyValueAccessDeniedException extends KeyValueStoreException {

    private static final long serialVersionUID = 1L;

    /**
     * @param message what was refused
     */
    public KeyValueAccessDeniedException(String message) {
        super(message);
    }
}
